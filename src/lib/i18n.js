const templatePatterns = Object.entries(english).filter(([key]) => /\{\w+\}/.test(key) && key !== "{value0} - {value1}").map(([key, value]) => {
  const names = [];
  const parts = key.split(/(\{\w+\})/g);
  const pattern = parts.map(part => {
    if (/^\{\w+\}$/.test(part)) { names.push(part.slice(1, -1)); return '(.*?)'; }
    return part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  }).join('');
  return { key, value, names, pattern: new RegExp('^' + pattern + '$') };
});
function interpolate(text, params) {
  return text.replace(/\{(\w+)\}/g, (match, key) => Object.hasOwn(params, key) ? String(params[key] ?? '') : match);
}
